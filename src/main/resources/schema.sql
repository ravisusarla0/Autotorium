CREATE TABLE IF NOT EXISTS part_category (
    category_id BIGINT PRIMARY KEY,
    name VARCHAR(50) NOT NULL
);

CREATE TABLE IF NOT EXISTS vehicle (
    vehicle_id BIGINT PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    type VARCHAR(50) NOT NULL,
    base_price DECIMAL(12, 2) NOT NULL,
    image_url VARCHAR(255) DEFAULT ''
);

CREATE TABLE IF NOT EXISTS part (
    part_id BIGINT PRIMARY KEY,
    category_id BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL,
    price_modifier DECIMAL(12, 2) NOT NULL,
    CONSTRAINT fk_part_category FOREIGN KEY (category_id) REFERENCES part_category(category_id)
);

CREATE TABLE IF NOT EXISTS vehicle_compatibility (
    vehicle_id BIGINT NOT NULL,
    part_id BIGINT NOT NULL,
    PRIMARY KEY (vehicle_id, part_id),
    CONSTRAINT fk_compat_vehicle FOREIGN KEY (vehicle_id) REFERENCES vehicle(vehicle_id),
    CONSTRAINT fk_compat_part FOREIGN KEY (part_id) REFERENCES part(part_id)
);

CREATE TABLE IF NOT EXISTS garage_build (
    build_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    build_name VARCHAR(120) NOT NULL,
    vehicle_id BIGINT NOT NULL,
    total_price DECIMAL(12, 2) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'IN_GARAGE',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_build_vehicle FOREIGN KEY (vehicle_id) REFERENCES vehicle(vehicle_id)
);

CREATE TABLE IF NOT EXISTS garage_build_part (
    build_id BIGINT NOT NULL,
    part_id BIGINT NOT NULL,
    PRIMARY KEY (build_id, part_id),
    CONSTRAINT fk_build_part_build FOREIGN KEY (build_id) REFERENCES garage_build(build_id),
    CONSTRAINT fk_build_part_part FOREIGN KEY (part_id) REFERENCES part(part_id)
);

CREATE TABLE IF NOT EXISTS build_ticket (
    ticket_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    build_id BIGINT NOT NULL,
    customer_name VARCHAR(100) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_ticket_build FOREIGN KEY (build_id) REFERENCES garage_build(build_id)
);
